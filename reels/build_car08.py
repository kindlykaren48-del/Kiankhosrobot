#!/usr/bin/env python3
"""کاروسل تصویری ۳ اسلایدی (بدون صدا) با قالب قفل‌شدهٔ ریل ۴:۵
عنوان بعدی بانک: «چرا نوزادت تا می‌گذاری‌اش زمین جیغ می‌زند؟»

خروجی: ۳ اسلاید PNG + نمای کلی + کپشن + ZIP در reels/carousel/car08_putdown/
ساخت: .venv/bin/python reels/build_car08.py
"""
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reel45_template import asset, build_carousel  # noqa: E402

SLUG = "car08_putdown"
EYEBROW = "نوزاد ۰ تا ۶ ماه"

DIS = ("⚠️ این محتوا آموزشی است و جایگزین ارزیابی پزشک نیست. "
       "اگر نگران فرزندت هستی، با پزشک کودک مشورت کن.")

SLIDES = [
    dict(palette="sage", image=asset("putdown_1.png"), cover=True,
         title="چرا نوزادت تا می‌گذاری‌اش زمین جیغ می‌زند؟",
         sub="مشکل از لوس بودنش نیست",
         tip="بدنش هنوز دنبال آغوش و صدای قلب توست"),
    dict(palette="warm", image=asset("putdown_2.png"),
         title="چرا آغوش را ترجیح می‌دهد؟",
         sub="سطح خالی، تغییر دما و رفلکس مورو؛ نزدیکی تو برایش یعنی امنیت",
         tip="بغل در ماه‌های اول لوس نمی‌کند"),
    dict(palette="mint", image=asset("putdown_3.png"),
         title="آرام‌تر زمین بگذار",
         sub="بعد از شیر و آروغ: آهسته پایین بیاور و دستت را چند ثانیه روی سینه‌اش نگه دار",
         tip="برای خواب: به پشت، سطح سفت و خالی",
         cta="ذخیره کن • برای مامان و بابای تازه بفرست"),
]

CAPTION = """👶 چرا نوزادت تا می‌گذاری‌اش زمین جیغ می‌زند؟

اگر نوزادت در آغوش آرام است اما تا روی زمین یا تشک می‌گذاری‌اش گریه می‌کند، معمولاً معنی‌اش «لوس شدن» نیست. در ماه‌های اول، نزدیکی به والد برایش یعنی گرما، بو، صدا و حس امنیت. جدا شدن ناگهانی، تغییر دما و سطح و گاهی رفلکس مورو (همان پرش ناگهانی دست‌ها) باعث می‌شود احساس ناامنی کند و با گریه صدایت بزند.

✅ چه کمکی می‌کند؟
• اول نیازهای پایه را چک کن: گرسنگی، آروغ، پوشک خشک، خواب‌آلودگی و گرما یا سرمای زیاد.
• پایین گذاشتن را تدریجی کن: بدنش را نزدیک بدنت نگه دار، آهسته پایین بیاور و دستت را چند ثانیه آرام روی سینه‌اش نگه دار و با صدایت آرامش کن.
• در زمان بیداری و آرامش، تمرین‌های کوتاه روی سطح امن داشته باش و صورت‌به‌صورت کنارش بمان؛ اگر نگاهش را برگرداند یا بی‌قرار شد، تمرین را تمام کن.
• برای خواب، قاعده تغییر نمی‌کند: همیشه به پشت، روی سطح سفت و تختِ خالی (بدون بالش، پتوی شل و اسباب‌بازی).
• اگر خودت خواب‌آلود یا خیلی خسته‌ای، نوزاد را در جای خواب امنش بگذار و چند دقیقه نفس بگیر؛ با نوزاد روی مبل یا صندلی خوابت نبرد.

🚨 با پزشک کودک یا اورژانس مشورت کن اگر گریه تسلی‌ناپذیر یا متفاوت از معمول است، در نوزاد زیر ۳ ماه تب دارد، شیر نمی‌خورد، پوشک خیس خیلی کم شده، بی‌حال است، تنفسش سخت است یا استفراغ مکرر دارد.

📌 این پست را ذخیره کن و برای یک مامان یا بابای تازه بفرست.

{dis}

#نوزاد #گریه_نوزاد #مادر_و_نوزاد #سلامت_کودک #والدین_آگاه #خواب_ایمن #بغل_کردن #دلبستگی_ایمن #نوزاد_تازه_متولد #تربیت_کودک
""".format(dis=DIS)


def main():
    outdir, files, ov_path, cap_path, _all_zip = build_carousel(
        SLUG, EYEBROW, SLIDES, CAPTION,
        ov_title=("تا می‌گذاری‌اش زمین", "جیغ می‌زند؟"), ov_palette="sage")

    total_bytes = sum(os.path.getsize(p) for p in files)
    for p in files:
        print(f"{os.path.basename(p)}: {os.path.getsize(p) / 1e6:.2f}MB")
    ok = "✓ زیر سقف ۴ مگابایت" if total_bytes <= 4_000_000 else "✗ بالای ۴ مگابایت!"
    print(f"POST TOTAL (مجموع اسلایدهای پست): {total_bytes / 1e6:.2f}MB — {ok}")
    assert total_bytes <= 4_000_000, "مجموع اسلایدها از سقف ۴ مگابایت رد شد"

    full = os.path.join(outdir, f"{SLUG}_full.zip")
    with zipfile.ZipFile(full, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files + [ov_path, cap_path]:
            z.write(p, os.path.basename(p))
    print(f"[✓] {SLUG}: {len(files)} اسلاید تصویری بدون صدا + نمای کلی + کپشن "
          f"+ ZIP کامل {os.path.getsize(full) / 1e6:.2f}MB → {outdir}")


if __name__ == "__main__":
    main()
