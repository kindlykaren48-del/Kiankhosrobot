def main():
    outdir = os.path.join(C.OUT, SLUG)
    os.makedirs(outdir, exist_ok=True)
    total = 4
    renders = [
        C.slide_cover(CFG, SKY, 1, total),
        C.slide_content(CFG, CORAL, SLIDE2, 2, total),
        C.slide_content(CFG, MINT, SLIDE3, 3, total),
        C.slide_content(CFG, LAV, SLIDE4, 4, total),
    ]
    files = []
    for i, img in enumerate(renders, start=1):
        p = os.path.join(outdir, f"{SLUG}_{i:02d}.png")
        img.convert("RGB").save(p, quality=94)
        files.append(p)
        print("saved", p, img.size)

    # نمای کلی ۲×۲
    tw, th = 540, 675
    overview = Image.new("RGB", (tw * 2, th * 2), (255, 255, 255))
    for i, p in enumerate(files):
        thumb = Image.open(p).resize((tw, th), Image.LANCZOS)
        overview.paste(thumb, ((i % 2) * tw, (i // 2) * th))
    overview.save(os.path.join(outdir, f"{SLUG}_overview.png"), quality=94)

    with open(os.path.join(outdir, f"{SLUG}_caption.txt"), "w", encoding="utf-8") as f:
        f.write(CAPTION)
    print(f"[✓] {SLUG}: 4 اسلاید مولتی‌کالر → {outdir}")


if __name__ == "__main__":
    main()
